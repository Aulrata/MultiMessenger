namespace MultiMessenger.Core.Enums;

/// <summary>
/// Роли образуют вложенность, а не разделение: администратор — это менеджер
/// с дополнительными правами. Он так же подключает свои каналы, ведёт свою переписку
/// и отправляет сообщения; админка добавляется сверху, ничего не отнимая.
/// <para>
/// Практическое следствие: при входе администратору выдаются обе роли в claims,
/// поэтому проверка «доступ к рабочему кабинету» пропускает и его тоже.
/// </para>
/// </summary>
public enum ManagerRole
{
    /// <summary>Сотрудник: свои каналы, свои диалоги, отправка и чтение сообщений.</summary>
    Manager,

    /// <summary>
    /// Всё то же самое плюс админка: создание и деактивация сотрудников,
    /// дашборд состояния каналов, статистика по сообщениям.
    /// Доступа к чужой переписке роль не даёт.
    /// </summary>
    Admin,
}
